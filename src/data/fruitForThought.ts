/**
 * Returns today's deterministic Fruit for Thought item based on local calendar date,
 * ensuring it automatically updates every single day of the year.
 */
export function getDailyFruitForThought(offsetDays = 0): FruitForThoughtItem {
  const now = new Date();
  if (offsetDays !== 0) {
    now.setDate(now.getDate() + offsetDays);
  }
  // Calculate day of the year (1 - 366)
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = Math.abs(dayOfYear) % FRUIT_FOR_THOUGHT_ITEMS.length;
  return FRUIT_FOR_THOUGHT_ITEMS[index];
}

/**
 * Returns formatted date string for today's thought banner
 */
export function getFormattedTodayString(): string {
  const now = new Date();
  return now.toLocaleDateString('en-US', {
    weekday: 'long',
    month: 'short',
    day: 'numeric',
  });
}
